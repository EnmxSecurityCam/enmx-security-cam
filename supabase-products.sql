-- ENMX Security Cam: catálogo público y administración privada de productos
-- Ejecutar una sola vez en Supabase SQL Editor.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  category text not null default 'Accesorios',
  price_dop numeric(12,2) not null default 0 check (price_dop >= 0),
  stock integer not null default 0 check (stock >= 0),
  images jsonb not null default '[]'::jsonb,
  image_url text,
  active boolean not null default true,
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.products enable row level security;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
drop policy if exists "Public can read active ENMX products" on public.products;
create policy "Public can read active ENMX products" on public.products
for select to anon using (active = true);
drop policy if exists "Authenticated admin can read ENMX products" on public.products;
create policy "Authenticated admin can read ENMX products" on public.products
for select to authenticated using (auth.uid() = 'bf585a90-413c-4330-9aef-12a702fd148d'::uuid);
drop policy if exists "ENMX admin can insert products" on public.products;
create policy "ENMX admin can insert products" on public.products
for insert to authenticated with check (auth.uid() = 'bf585a90-413c-4330-9aef-12a702fd148d'::uuid);
drop policy if exists "ENMX admin can update products" on public.products;
create policy "ENMX admin can update products" on public.products
for update to authenticated using (auth.uid() = 'bf585a90-413c-4330-9aef-12a702fd148d'::uuid)
with check (auth.uid() = 'bf585a90-413c-4330-9aef-12a702fd148d'::uuid);
drop policy if exists "ENMX admin can delete products" on public.products;
create policy "ENMX admin can delete products" on public.products
for delete to authenticated using (auth.uid() = 'bf585a90-413c-4330-9aef-12a702fd148d'::uuid);
grant usage, select on sequence public.products_id_seq to authenticated;
